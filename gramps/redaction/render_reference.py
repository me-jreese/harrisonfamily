#!/usr/bin/env python3
"""Render docs/reference/redaction-policy.md from gramps/redaction/redaction-v1.json (task redaction-policy-v1). Standard library only.

    python3 gramps/redaction/render_reference.py           # rewrite the page
    python3 gramps/redaction/render_reference.py --check   # exit 1 when the page differs from the policy

The page has no hand-written facts: every list, pattern and rule row comes from the JSON, so the two cannot drift
(gramps/tests/unit/test_redaction_policy.py fails when they do).
"""
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.abspath(os.path.join(HERE, "..", ".."))
POLICY = os.path.join(HERE, "redaction-v1.json")
PAGE = os.path.join(REPO, "docs", "reference", "redaction-policy.md")

CLASS_ORDER = [
    ("private", "Private flag and what only private objects reach (sync.md 5.1)"),
    ("birth", "Dates of birth and local-only attributes (sync.md 5.2)"),
    ("contact", "Contact information (sync.md 5.3)"),
    ("place", "Places (sync.md 5.3)"),
    ("scan", "Free-text scan (sync.md 5.4)"),
    ("media", "Media (sync.md 5.5)"),
]
ACTIONS = {
    "exclude_object": "The whole object stays out of the cloud (or is held).",
    "filter_element": "An element or a reference is removed from its list, or a handle is nulled.",
    "local_only": "A field or element stays on the desktop; the cloud gets the empty value.",
    "reduce_date": "A Date loses day, month and text and keeps its year.",
    "repoint_place": "A reference to an excluded place moves to the nearest kept ancestor.",
    "round_coordinates": "A coordinate is rounded to the policy's decimals.",
    "hold_media": "A Media object stays out of the cloud until io releases it.",
    "scan": "A hit of the shared detector in an outgoing text field holds the field, or the whole object when it is new.",
}


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def code(text):
    return "`%s`" % str(text).replace("`", "'")


def named(items):
    return ", ".join("%s %d" % (i["name"], i["value"]) for i in items)


def table(header, rows):
    out = ["| " + " | ".join(header) + " |", "| " + " | ".join("---" for _ in header) + " |"]
    out += ["| " + " | ".join(cell(c) for c in row) + " |" for row in rows]
    return out


def pattern(spec):
    return "/%s/%s" % (spec["pattern"], spec["flags"])


def render(policy):
    L = []
    add = L.append
    add("# Redaction policy v1")
    add("")
    add("<!-- Generated by gramps/redaction/render_reference.py from gramps/redaction/redaction-v1.json. Do not edit by hand: change the JSON, regenerate, and commit both. -->")
    add("")
    add("What never goes to the cloud, as one declarative rule file. This page is generated from `gramps/redaction/redaction-v1.json`; "
        "a unit test fails when the two differ. Rationale for the privacy model is in [The privacy model for family data](../explanation/family-data-privacy.md).")
    add("")
    add("Basis: " + "; ".join(policy["basis"]) + ".")
    add("")
    add("## Where the policy lives")
    add("")
    add("| Path | What it is |")
    add("| --- | --- |")
    add("| `gramps/redaction/redaction-v1.json` | The rules, the birth-like list and the tables below. The only source. |")
    add("| `gramps/redaction/redaction-v1.schema.json` | The JSON Schema the file validates against. |")
    add("| `gramps/redaction/vectors/*.json` | Golden vectors: input objects, the expected projection, the expected holds and the server validator's verdict. Python and JavaScript both pass them. |")
    add("| `gramps/redaction/make_vectors.py` | Generates the vectors; `--check` compares bytes. |")
    add("| `gramps/hfygramps/rules.py` | The Python loader and the pure predicates, `is_birth_like` first. |")
    add("| `shared/redaction-rules.mjs` | The JavaScript port of the same predicates, the URL channel rules and the pointer matcher; it takes the parsed policy as an argument. |")
    add("| `api/src/sync/checker.js` | The server validator's privacy checker: every rule marked `server: detect`, run on every write. It reproduces `expected.server` of every vector. |")
    add("| `gramps/tests/unit/redaction_oracle.py` | Test-only reference reading of the rules that the vectors are checked against. It is neither the projection nor the server validator. |")
    add("")
    add("The projection, the server validator, the edit guard and the renderer are to import this one file and keep no list of their own (D2-32).")
    add("")
    add("## Order of application")
    add("")
    add("The projection `P(tree)` is a pure function of the whole local tree. Each rule names the phase it belongs to.")
    add("")
    for ph in sorted(policy["phases"], key=lambda p: p["order"]):
        add("%d. **%s.** %s" % (ph["order"], ph["id"], ph["summary"]))
    add("")
    add("## Birth-like events")
    add("")
    bl = policy["birthLike"]
    add(bl["summary"])
    add("")
    add("An event is birth-like when any of these holds, for %s:" % bl["appliesTo"])
    add("")
    add("- Its type is one of: %s." % named(bl["eventTypes"]))
    add("- Its type is Custom (%d) and the type name matches %s (a substring match; ASCII case folding only, and a deliberate over-match that fails closed: Birthright and Baptist are held back like a birth)." % (bl["customType"]["value"], code(pattern(bl["customType"]))))
    if bl["birthRefIndex"]:
        add("- Some person references it at its `birth_ref_index`, whatever its type.")
    add("")
    d = policy["dates"]
    add("Day and month mean `dateval` indexes %s. A date of a birth-like event is reduced to:" % ", ".join(str(i) for i in d["dayMonthIndexes"]))
    add("")
    add("- Those indexes set to 0, in both halves of a RANGE or SPAN; the years (indexes %s), the slash flags, the modifier, the quality, the calendar and the new-year flag unchanged." % ", ".join(str(i) for i in d["yearIndexes"]))
    add("- `text` set to the empty string. The server accepts only a bare year (%s) or nothing." % code(d["bareYearTextPattern"]))
    add("- A TEXTONLY date (modifier %d) becomes a plain date with the first four-digit year of its text (%s, group 1), or an empty date when the text has none." % (d["textOnlyModifier"], code(d["textOnlyYearPattern"])))
    add("- `sortval` recomputed as the day number of January 1 of the year in the date's calendar, for the calendars %s (Gregorian 0, Julian 1), and 0 when the year is 0 or the calendar is another." % ", ".join(str(c) for c in d["sortvalCalendars"]))
    add("")
    add("A name of type Birth (name type %d) and a citation referenced by a birth-like event or by its EventRef are reduced the same way." % d["nameTypeBirth"])
    add("")
    add("## Rules")
    add("")
    add("Each rule has an id, a class, the Gramps classes it applies to, a path pattern, an action and a phase. Path patterns are RFC 6901 pointers in which `*` is one key or list index, `**` is any depth (including none) and `{a,b}` lists alternatives. "
        "`server` says whether the server validator detects a violation of the rule (`detect`) or cannot (`none`: it needs local data, bytes or the whole local tree). "
        "A rule marked desktop-only needs data the cloud never holds.")
    add("")
    add("### Actions")
    add("")
    used = []
    for r in policy["rules"]:
        if r["action"] not in used:
            used.append(r["action"])
    for a in sorted(used):
        add("- %s: %s" % (code(a), ACTIONS.get(a, "")))
    add("")
    by_class = {}
    for r in policy["rules"]:
        by_class.setdefault(r["class"], []).append(r)
    for cls, heading in CLASS_ORDER:
        rules = by_class.get(cls, [])
        if not rules:
            continue
        add("### " + heading)
        add("")
        rows = []
        for r in rules:
            flags = r["server"] + (", desktop-only" if r.get("desktopOnly") else "")
            rows.append([code(r["id"]), ", ".join(r["objectClass"]), code(r["path"]), code(r["action"]), r["phase"], flags, r["summary"] + " (" + r["source"] + ")"])
        L.extend(table(["Rule", "Classes", "Path", "Action", "Phase", "Server", "What it does (source)"], rows))
        add("")
    add("## Tables the rules read")
    add("")
    add("### Attributes")
    add("")
    add("- Local-only age and time attributes: %s." % named(policy["attributes"]["ageAndTime"]))
    add("- Local-only government identifiers: %s." % named(policy["attributes"]["governmentId"]))
    add("")
    add("### Contact URLs")
    add("")
    u = policy["urls"]
    add("- URL type %d (Email) is local-only." % u["emailType"])
    add("- Schemes: %s." % ", ".join(code(s + ":") for s in u["schemes"]))
    add("- Hosts, matched by registrable-domain suffix and never by substring: %s." % ", ".join(code(h) for h in u["hosts"]))
    add("- Paths: %s." % ", ".join(code(p["host"] + p["prefix"]) for p in u["paths"]))
    add("- A backslash is read as a slash before the scheme, host and path are split, as a browser does.")
    add("")
    add("### Places")
    add("")
    p = policy["places"]
    add("- Excluded by type: %s." % named(p["excludedTypes"]))
    add("- Excluded when the type is Custom (%d) and its name matches %s. This is a substring match, so a name that merely contains one of the words (Chapter, Charlotte, Pilot, Homestead District) is excluded too. The over-match is deliberate and fails closed: it drops a harmless place and never lets a home through." % (p["customHomeLike"]["value"], code(pattern(p["customHomeLike"]))))
    add("- A place code stays only for: %s. Every other type keeps it local." % named(p["administrativeTypes"]))
    add("- Alternate-location fields blanked: %s." % ", ".join(code(f) for f in p["locationFields"]))
    add("- Coordinates: a plain decimal (%s) is rounded half away from zero to %d decimals, and a value with no more decimals keeps its text; anything else is blanked." % (code(p["coordinatePattern"]), p["coordinateDecimals"]))
    add("")
    add("### Media")
    add("")
    m = policy["media"]
    add("- Held until io releases them, by mime type: %s." % ", ".join(code(x) for x in m["heldMime"]))
    add("- Held when the file has EXIF GPS latitude or longitude, by mime type: %s." % ", ".join(code(x) for x in m["exifGpsMime"]))
    add("- A media reference rectangle is four integers from %d to %d with x1 < x2 and y1 < y2. %s is normalised to null; any other shape is held." % (m["rectRange"][0], m["rectRange"][1], code(json.dumps(m["fullFrameRect"]))))
    add("")
    add("### Free-text scan")
    add("")
    s = policy["scan"]
    add("- Detector kinds (the one R-18 detector, `shared/privacy-guard.mjs` and `gramps/hfygramps/scanner.py`): %s." % ", ".join(code(k) for k in s["kinds"]))
    add("- Desktop-only kinds: %s. The window for a birth keyword or a name is %d characters." % (", ".join(code(k) for k in s["desktopOnlyKinds"]), s["dobWindow"]))
    add("- A hit on an existing synced object keeps the last synced value of that field; a hit on a new object holds the whole object, and references to it are filtered. A styled note is one atomic field: holding it keeps the base tags too.")
    add("")
    L.extend(table(["Class", "Scanned field"], [[f["class"], code(f["path"])] for f in s["fields"]]))
    add("")
    readings = [r for r in policy["rules"] if "reading recorded" in r["source"]]
    if readings:
        add("## Readings this file records")
        add("")
        add("The design leaves these open; the file fixes them, and each is raised for confirmation.")
        add("")
        for r in readings:
            add("- %s: %s" % (code(r["id"]), r["summary"]))
        add("")
    add("## Vectors")
    add("")
    add("`gramps/redaction/vectors/<group>.json` holds `{policy, group, vectors}`. A vector is `{id, title, rules, context, input, expected}`:")
    add("")
    add("- `input` is a list of partial Gramps `json_data` objects; every nested element carries its `_class`, and a missing key means the Gramps default.")
    add("- `context` may hold `base` (the last synced projected object per handle), `files` (per media handle: `exif_gps`, `md5`, `readable`), `released` (media handles io released) and `sticky` (event handles that were ever birth-like).")
    add("- `expected.projection` maps every input handle to the projected object, or to `null` when it is excluded or held and never synced. `expected.excluded` lists `{handle, rule}`; `expected.holds` lists `{handle, rule, scope, pointer}` with scope `object` or `field`.")
    add("- `expected.server` is the server validator's verdict on `input` as submitted: `{ok, violations: [{rule, handle, pointer}]}`, pointers per RFC 6901. The projection of every input must itself pass.")
    add("- `expected.birth_like`, when present, lists the events `isBirthLike` must accept.")
    add("- `rules` names the rule ids the vector exercises. Every rule id is named by at least one vector.")
    add("")
    add("Regenerate and check:")
    add("")
    add("```bash")
    add("python3 gramps/redaction/make_vectors.py            # rewrite the vectors")
    add("python3 gramps/redaction/render_reference.py        # rewrite this page")
    add("python3 -m unittest discover gramps/tests/unit      # the checks, including both drift tests")
    add("cd api && npx vitest run test/redaction-rules.test.js   # the JavaScript port against the same vectors")
    add("```")
    add("")
    add("## Not in this file")
    add("")
    add("- Non-birth dates are stored at full precision and published as years only; that is the renderer's rule (Q2-04b), not part of the projection.")
    add("- The scan of members' posts, comments and chat is the shared detector (`shared/privacy-guard.mjs`), not a rule here.")
    add("- The merge, lift and conflict rules (sync.md section 6) read this policy but do not live in it.")
    add("")
    return "\n".join(L) + "\n"


def main(argv):
    with open(POLICY, encoding="utf-8") as fh:
        text = render(json.load(fh))
    if "--check" in argv:
        have = open(PAGE, encoding="utf-8").read() if os.path.exists(PAGE) else None
        if have != text:
            print("docs/reference/redaction-policy.md is stale: run python3 gramps/redaction/render_reference.py", file=sys.stderr)
            return 1
        return 0
    with open(PAGE, "w", encoding="utf-8") as fh:
        fh.write(text)
    print("wrote", PAGE)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
