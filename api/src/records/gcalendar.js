// Gramps calendar arithmetic (HFY-TSK-249, edit-gramps-semantics): a port of the `*_sdn` functions of Gramps 6.0.6
// `gramps/gen/lib/gcalendar.py`, so the server computes a Date's `sortval` the way Gramps' own Date does.
//
// An SDN ("serial day number") is the Julian day number: the days elapsed since Monday, January 1, 4713 BC in the
// proleptic Julian calendar. Gramps stores it in `Date.sortval`.
//
// PURE. No import of any kind, no clock: it runs under `node --test` and in a browser. Nothing calls it yet but
// `semantics.js`, which no route reaches (its first caller is `edit-api-changes`).
//
// Python's `//` and `%` floor, JavaScript's `/` and `%` truncate: `fdiv` and `fmod` keep the Python meaning, so a
// negative year or month gives the same number as Gramps. Every value that Gramps shifts with `<<`/`>>` is done with
// arithmetic here instead, because JavaScript's bit operators are 32-bit signed.
//
// Verified against Gramps itself by `api/test/records/fixtures/gramps-semantics.golden.json` (generated by
// `scripts/records/gen-gramps-semantics-goldens.py`).

const fdiv = (a, b) => Math.floor(a / b);
const fmod = (a, b) => ((a % b) + b) % b;

// ---- Gregorian and Julian -------------------------------------------------------------------------------------
const GRG_SDN_OFFSET = 32045;
const GRG_DAYS_PER_5_MONTHS = 153;
const GRG_DAYS_PER_4_YEARS = 1461;
const GRG_DAYS_PER_400_YEARS = 146097;
const JLN_SDN_OFFSET = 32083;

export function gregorianSdn(year, month, day) {
  year += year < 0 ? 4801 : 4800;
  if (month > 2) month -= 3;
  else {
    month += 9;
    year -= 1;
  }
  return (
    fdiv(fdiv(year, 100) * GRG_DAYS_PER_400_YEARS, 4) +
    fdiv(fmod(year, 100) * GRG_DAYS_PER_4_YEARS, 4) +
    fdiv(month * GRG_DAYS_PER_5_MONTHS + 2, 5) +
    day -
    GRG_SDN_OFFSET
  );
}

export function julianSdn(year, month, day) {
  year += year < 0 ? 4801 : 4800;
  if (month > 2) month -= 3;
  else {
    month += 9;
    year -= 1;
  }
  return fdiv(year * GRG_DAYS_PER_4_YEARS, 4) + fdiv(month * GRG_DAYS_PER_5_MONTHS + 2, 5) + day - JLN_SDN_OFFSET;
}

// ---- Hebrew ---------------------------------------------------------------------------------------------------
const HBR_HALAKIM_PER_HOUR = 1080;
const HBR_HALAKIM_PER_DAY = 25920;
const HBR_HALAKIM_PER_LUNAR_CYCLE = 29 * HBR_HALAKIM_PER_DAY + 13753;
const HBR_HALAKIM_PER_METONIC_CYCLE = HBR_HALAKIM_PER_LUNAR_CYCLE * (12 * 19 + 7);
const HBR_SDN_OFFSET = 347997;
const HBR_NEW_MOON_OF_CREATION = 31524;
const HBR_NOON = 18 * HBR_HALAKIM_PER_HOUR;
const HBR_AM3_11_20 = 9 * HBR_HALAKIM_PER_HOUR + 204;
const HBR_AM9_32_43 = 15 * HBR_HALAKIM_PER_HOUR + 589;
const HBR_SUNDAY = 0;
const HBR_MONDAY = 1;
const HBR_TUESDAY = 2;
const HBR_WEDNESDAY = 3;
const HBR_FRIDAY = 5;
const HBR_MONTHS_PER_YEAR = [12, 12, 13, 12, 12, 13, 12, 13, 12, 12, 13, 12, 12, 13, 12, 12, 13, 12, 13];
const HBR_YEAR_OFFSET = [0, 12, 24, 37, 49, 61, 74, 86, 99, 111, 123, 136, 148, 160, 173, 185, 197, 210, 222];

function tishri1(metonicYear, moladDay, moladHalakim) {
  let t1 = moladDay;
  let dow = fmod(t1, 7);
  const leapYear = [2, 5, 7, 10, 13, 16, 18].includes(metonicYear);
  const lastWasLeapYear = [3, 6, 8, 11, 14, 17, 0].includes(metonicYear);
  if (
    moladHalakim >= HBR_NOON ||
    (!leapYear && dow === HBR_TUESDAY && moladHalakim >= HBR_AM3_11_20) ||
    (lastWasLeapYear && dow === HBR_MONDAY && moladHalakim >= HBR_AM9_32_43)
  ) {
    t1 += 1;
    dow += 1;
    if (dow === 7) dow = 0;
  }
  if (dow === HBR_WEDNESDAY || dow === HBR_FRIDAY || dow === HBR_SUNDAY) t1 += 1;
  return t1;
}

// Gramps splits the product into 16-bit halves with shifts; with plain arithmetic the result is the same number.
function moladOfMetonicCycle(metonicCycle) {
  let r1 = HBR_NEW_MOON_OF_CREATION;
  r1 += metonicCycle * (HBR_HALAKIM_PER_METONIC_CYCLE % 65536);
  let r2 = Math.floor(r1 / 65536);
  r2 += metonicCycle * (Math.floor(HBR_HALAKIM_PER_METONIC_CYCLE / 65536) % 65536);
  const d2 = Math.floor(r2 / HBR_HALAKIM_PER_DAY);
  r2 -= d2 * HBR_HALAKIM_PER_DAY;
  r1 = r2 * 65536 + (r1 % 65536);
  const d1 = Math.floor(r1 / HBR_HALAKIM_PER_DAY);
  r1 -= d1 * HBR_HALAKIM_PER_DAY;
  return [d2 * 65536 + d1, r1];
}

function startOfYear(year) {
  const metonicCycle = fdiv(year - 1, 19);
  const metonicYear = fmod(year - 1, 19);
  let [moladDay, moladHalakim] = moladOfMetonicCycle(metonicCycle);
  moladHalakim += HBR_HALAKIM_PER_LUNAR_CYCLE * HBR_YEAR_OFFSET[metonicYear];
  moladDay += fdiv(moladHalakim, HBR_HALAKIM_PER_DAY);
  moladHalakim = fmod(moladHalakim, HBR_HALAKIM_PER_DAY);
  return { metonicCycle, metonicYear, moladDay, moladHalakim, ptishri1: tishri1(metonicYear, moladDay, moladHalakim) };
}

export function hebrewSdn(year, month, day) {
  let sdn;
  if (month === 1 || month === 2) {
    const s = startOfYear(year);
    sdn = month === 1 ? s.ptishri1 + day - 1 : s.ptishri1 + day + 29;
  } else if (month === 3) {
    const s = startOfYear(year);
    let { moladDay, moladHalakim } = s;
    moladHalakim += HBR_HALAKIM_PER_LUNAR_CYCLE * HBR_MONTHS_PER_YEAR[s.metonicYear];
    moladDay += fdiv(moladHalakim, HBR_HALAKIM_PER_DAY);
    moladHalakim = fmod(moladHalakim, HBR_HALAKIM_PER_DAY);
    const tishri1After = tishri1(fmod(s.metonicYear + 1, 19), moladDay, moladHalakim);
    const yearLength = tishri1After - s.ptishri1;
    sdn = yearLength === 355 || yearLength === 385 ? s.ptishri1 + day + 59 : s.ptishri1 + day + 58;
  } else if (month === 4 || month === 5 || month === 6) {
    const after = startOfYear(year + 1).ptishri1;
    const lengthOfAdar1And2 = HBR_MONTHS_PER_YEAR[fmod(year - 1, 19)] === 12 ? 29 : 59;
    if (month === 4) sdn = after + day - lengthOfAdar1And2 - 237;
    else if (month === 5) sdn = after + day - lengthOfAdar1And2 - 208;
    else sdn = after + day - lengthOfAdar1And2 - 178;
  } else {
    const after = startOfYear(year + 1).ptishri1;
    const back = { 7: 207, 8: 178, 9: 148, 10: 119, 11: 89, 12: 60, 13: 30 }[month];
    if (back === undefined) return 0;
    sdn = after + day - back;
  }
  return sdn + HBR_SDN_OFFSET;
}

// ---- French Republican, Persian, Islamic, Swedish ---------------------------------------------------------------
const FR_SDN_OFFSET = 2375474;
const PRS_EPOCH = 1948320.5;
const ISM_EPOCH = 1948439.5;

export function frenchSdn(year, month, day) {
  return fdiv(year * 1461, 4) + (month - 1) * 30 + day + FR_SDN_OFFSET;
}

export function persianSdn(year, month, day) {
  const epbase = year >= 0 ? year - 474 : year - 473;
  const epyear = 474 + fmod(epbase, 2820);
  const v1 = month <= 7 ? (month - 1) * 31 : (month - 1) * 30 + 6;
  const v2 = fdiv(epyear * 682 - 110, 2816);
  const v3 = (epyear - 1) * 365 + day;
  const v4 = fdiv(epbase, 2820) * 1029983;
  return Math.ceil(v1 + v2 + v3 + v4 + PRS_EPOCH - 1);
}

export function islamicSdn(year, month, day) {
  const v1 = Math.ceil(29.5 * (month - 1));
  const v2 = (year - 1) * 354;
  const v3 = fdiv(3 + 11 * year, 30);
  return Math.ceil(day + v1 + v2 + v3 + ISM_EPOCH - 1);
}

const tupleCmp = (a, b) => {
  for (let i = 0; i < 3; i++) if (a[i] !== b[i]) return a[i] < b[i] ? -1 : 1;
  return 0;
};

export function swedishSdn(year, month, day) {
  const d = [year, month, day];
  if (tupleCmp([1700, 3, 1], d) <= 0 && tupleCmp(d, [1712, 2, 30]) <= 0) return julianSdn(year, month, day) - 1;
  if (tupleCmp([1753, 3, 1], d) <= 0) return gregorianSdn(year, month, day);
  return julianSdn(year, month, day);
}

// Date.CAL_* order: Gregorian, Julian, Hebrew, French, Persian, Islamic, Swedish.
export const CALENDAR_SDN = Object.freeze([gregorianSdn, julianSdn, hebrewSdn, frenchSdn, persianSdn, islamicSdn, swedishSdn]);

export function sdn(calendar, year, month, day) {
  const f = CALENDAR_SDN[calendar];
  if (!f) throw new RangeError(`unknown Gramps calendar ${calendar}`);
  return f(year, month, day);
}
