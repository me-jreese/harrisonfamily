  // Island loader pattern: HFYFeatureFlags.loadIsland("name") injects /js/islands/<name>.js (+ .css) once.
  // Every requested island has a settle promise: true once its module graph has loaded and run, false on a 404 or
  // network failure (the loader then drops any preview override and the caller's onError restores the legacy UI).
  const islands = {};
  function islandEntry(name) {
    if (!islands[name]) {
      let settle = null;
      const promise = new Promise((resolve) => {
        settle = resolve;
      });
      islands[name] = { promise, settle, script: null };
    }
    return islands[name];
  }
  function loadIsland(name, { onError, onLoad } = {}) {
    const entry = islandEntry(name);
    if (entry.script) return entry.script;
    // ?v=<sha8 of the entry> (ASSET_V.islands, stamped by the build): the entry URL changes whenever its bytes do, so neither the
    // browser nor Cloudflare can hand back an old entry that imports chunks the new deploy no longer has. Its chunk imports are
    // relative and content-hashed by esbuild (chunks/chunk-<hash>.js), so they need no query.
    const version = (ASSET_V.islands && ASSET_V.islands[name]) || {};
    const css = document.createElement("link");
    css.rel = "stylesheet";
    css.href = assetUrl("/js/islands/" + name + ".css", version.css);
    const script = document.createElement("script");
    script.type = "module";
    script.src = assetUrl("/js/islands/" + name + ".js", version.js);
    script.onload = function () {
      entry.settle(true);
      if (onLoad) onLoad();
    };
    script.onerror = function () {
      entry.settle(false);
      css.remove();
      flagUnavailable(`island "${name}"`);
      if (onError) onError();
    };
    entry.script = script;
    // CSS first: the module is appended only once the island stylesheet has applied (load) or failed (error), so an island never
    // mounts unstyled and never paints before its rules land.
    let appended = false;
    const appendScript = function () {
      if (appended) return;
      appended = true;
      document.head.appendChild(script);
    };
    css.onload = appendScript;
    css.onerror = appendScript;
    document.head.appendChild(css);
    return script;
  }
