#!/usr/bin/env node
// The sync error catalog test map (HFY-TSK-150, review SI-21; sync.md section 17 as amended by BRD2 section 11.1).
//
// The catalog has 52 desktop rows (D01-D52) and 22 cloud rows (S01-S22). scripts/ci/sync-error-catalog.json maps every row to the
// named tests that trigger it. This script fails when:
//   - a row has no entry, an entry has no test, or a row's failure text is empty (a gap);
//   - the map holds a row ID outside D01-D52 and S01-S22 (an unknown ID);
//   - a mapped test is not declared in its file (a renamed or deleted test), is skipped, or is not a runnable test, or its file is outside
//     the test suites;
//   - one of the wire codes the write path answers with (WIRE_KEYS: the validator's 4xx refusals, HFY-TSK-245) has no entry or no test;
//   - docs/reference/sync-error-catalog.md is not what this script renders from the map (a drift).
// It reads files and nothing else: no install, no network, no CodeArtifact (HFY-R62), so it runs in the ci.manifest.yaml `tests` list.
//
// A test name is the declaration the file holds, found by file type:
//   .py   the method name: `def test_x(self)` inside a class that has a base class (unittest finds nothing else), not under an
//         unconditional @unittest.skip or @skip
//   .js   the exact title string of an `it("...")` or `test("...")` call (the title has no template placeholders), not `.skip` or `.todo`
//   .sh   the label of a `CURRENT="..."` line in the infra test runner
//
// Usage: node scripts/ci/check-sync-catalog.mjs [--root <repo>] [--write-doc]
//   --write-doc  rewrite the two tables in the reference page from the map, then check
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(HERE, '..', '..');
export const MAP_PATH = 'scripts/ci/sync-error-catalog.json';
export const DOC_PATH = 'docs/reference/sync-error-catalog.md';
export const DOC_START = '<!-- sync-error-catalog:start (generated by scripts/ci/check-sync-catalog.mjs --write-doc) -->';
export const DOC_END = '<!-- sync-error-catalog:end -->';
export const WIRE_START = '<!-- sync-wire-codes:start (generated by scripts/ci/check-sync-catalog.mjs --write-doc) -->';
export const WIRE_END = '<!-- sync-wire-codes:end -->';

export const DESKTOP_ROWS = 52;
export const CLOUD_ROWS = 22;

/** Where a test may live, with the suite that runs it (the label in the reference page). */
export const SUITES = [
  { prefix: 'gramps/tests/unit/', label: 'Gramps unit (python3 -m unittest discover gramps/tests/unit)' },
  { prefix: 'gramps/tests/e2e/', label: 'Gramps e2e (gramps/tests/e2e/run.sh, Gramps 6.0.6 and the dev server)' },
  { prefix: 'gramps/tests/gramps/', label: 'Gramps lane (gramps/tests/gramps/run.sh, Gramps 6.0.6)' },
  { prefix: 'api/test/', label: 'api (cd api && npm test)' },
  { prefix: 'scripts/infra/test/', label: 'infra (bash scripts/infra/test/run.sh)' },
];

/**
 * The refusals the sync write path (api/src/sync, validator.js and apply.js) answers with on the wire, each with its own named test
 * (HFY-TSK-245 addendum). A key is `<status> <code>` and, for a code that carries rules, ` <rule>` (the rule in details.violations).
 * `schema.*` and `media.rect.*` stand for every rule of that family. Adding a wire code to the write path means adding it here and
 * to the map's "wire" object.
 */
export const WIRE_KEYS = [
  '422 integrity_violation id.shape',
  '422 integrity_violation id.reserved_name',
  '422 integrity_violation integrity.unresolved_reference',
  '422 integrity_violation integrity.symmetry.spouse',
  '422 integrity_violation integrity.symmetry.child',
  '422 integrity_violation integrity.index_range',
  '400 validation schema.*',
  '400 validation media.rect.*',
  '409 reserved_id_block',
  '409 renumber_blocked',
  '409 gramps_id_retired',
  '403 step_up_required',
  '403 step_up_required heads_unknown',
  '422 withdrawn_reference',
];

export function expectedIds() {
  const ids = [];
  for (let i = 1; i <= DESKTOP_ROWS; i += 1) ids.push(`D${String(i).padStart(2, '0')}`);
  for (let i = 1; i <= CLOUD_ROWS; i += 1) ids.push(`S${String(i).padStart(2, '0')}`);
  return ids;
}

function idOrder(id) {
  return (id[0] === 'D' ? 0 : 1000) + Number(id.slice(1));
}

// ---- finding a declaration in a file

function unquote(literal) {
  const q = literal[0];
  const body = literal.slice(1, -1);
  if (q === '`') return body.includes('${') ? null : body.replace(/\\(.)/g, '$1');
  try {
    return q === '"' ? JSON.parse(literal) : JSON.parse(`"${body.replace(/\\'/g, "'").replace(/"/g, '\\"')}"`);
  } catch {
    return null;
  }
}

/** The runnable test methods of a Python file: `def test*` in a class with a base class, none under an unconditional skip. */
function pythonTests(text) {
  const names = new Set();
  let inTestClass = false;
  let decorators = [];
  for (const line of text.split('\n')) {
    if (/^\s*@/.test(line)) {
      decorators.push(line);
      continue;
    }
    const skipped = decorators.some((d) => /^\s*@(?:unittest\.)?skip\b/.test(d) || /^\s*@(?:unittest\.)?expectedFailure\b/.test(d));
    const cls = /^class[ \t]+\w+[ \t]*\(([^)]*)\)[ \t]*:/.exec(line);
    if (cls) {
      inTestClass = cls[1].trim() !== '' && !skipped;
    } else if (/^[A-Za-z_]/.test(line)) {
      inTestClass = false; // a top-level def, import or assignment ends the class body
    } else {
      const m = /^[ \t]+(?:async[ \t]+)?def[ \t]+(test[A-Za-z0-9_]*)[ \t]*\(/.exec(line);
      if (m && inTestClass && !skipped) names.add(m[1]);
    }
    if (line.trim() !== '') decorators = [];
  }
  return names;
}

export function declaredNames(file, text) {
  const names = new Set();
  if (file.endsWith('.py')) {
    return pythonTests(text);
  } else if (/\.(?:m?js|cjs)$/.test(file)) {
    const re = /\b(?:it|test)(\.\w+)?\(\s*("(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\]|\\.)*`)/g;
    for (const m of text.matchAll(re)) {
      if (m[1] === '.skip' || m[1] === '.todo') continue;
      const title = unquote(m[2]);
      if (title !== null) names.add(title);
    }
  } else if (file.endsWith('.sh')) {
    for (const m of text.matchAll(/^\s*CURRENT="([^"\n]*)"/gm)) names.add(m[1]);
  }
  return names;
}

// ---- the check

export function check({ root = DEFAULT_ROOT, writeDoc = false } = {}) {
  const problems = [];
  const fail = (msg) => problems.push(msg);
  const mapFile = resolve(root, MAP_PATH);
  if (!existsSync(mapFile)) return { problems: [`${MAP_PATH} is missing`], rows: 0, tests: 0 };
  let map;
  try {
    map = JSON.parse(readFileSync(mapFile, 'utf8'));
  } catch (err) {
    return { problems: [`${MAP_PATH} is not JSON (${err.message})`], rows: 0, tests: 0 };
  }
  if (!map || typeof map !== 'object' || map.version !== 1 || !map.rows || typeof map.rows !== 'object' || Array.isArray(map.rows)) {
    return { problems: [`${MAP_PATH} must be {"version": 1, "rows": {...}}`], rows: 0, tests: 0 };
  }

  const expected = new Set(expectedIds());
  for (const id of Object.keys(map.rows)) {
    if (!expected.has(id)) fail(`unknown row ID ${id}: the catalog has D01-D${DESKTOP_ROWS} and S01-S${String(CLOUD_ROWS).padStart(2, '0')}`);
  }

  const fileCache = new Map();
  const namesOf = (file) => {
    if (!fileCache.has(file)) {
      const full = resolve(root, file);
      fileCache.set(file, existsSync(full) ? declaredNames(file, readFileSync(full, 'utf8')) : null);
    }
    return fileCache.get(file);
  };

  let testCount = 0;
  /** One map entry (a row or a wire code): failure text, at least one test, every test declared in a suite file. */
  const checkEntry = (id, entry, what) => {
    if (!entry || typeof entry !== 'object') {
      fail(`gap: ${what} ${id} has no entry`);
      return;
    }
    if (typeof entry.failure !== 'string' || !entry.failure.trim()) fail(`gap: ${what} ${id} has no failure text`);
    if (!Array.isArray(entry.tests) || entry.tests.length === 0) {
      fail(`gap: ${what} ${id} has no test`);
      return;
    }
    const seen = new Set();
    for (const t of entry.tests) {
      testCount += 1;
      if (!t || typeof t.file !== 'string' || typeof t.name !== 'string' || !t.file || !t.name) {
        fail(`${id}: a test entry needs a file and a name`);
        continue;
      }
      const tag = `${id}: ${t.file} :: ${t.name}`;
      if (seen.has(`${t.file}::${t.name}`)) fail(`${tag} is listed twice`);
      seen.add(`${t.file}::${t.name}`);
      if (t.file.includes('..') || t.file.startsWith('/')) {
        fail(`${tag}: the file must be a path inside the repository`);
        continue;
      }
      if (!SUITES.some((s) => t.file.startsWith(s.prefix))) {
        fail(`${tag}: the file is not in a test suite (${SUITES.map((s) => s.prefix).join(', ')})`);
        continue;
      }
      const names = namesOf(t.file);
      if (names === null) fail(`${tag}: the file does not exist`);
      else if (!names.has(t.name)) fail(`${tag}: no such test in the file (renamed, deleted, skipped, or not a runnable test)`);
    }
  };

  for (const id of expectedIds()) checkEntry(id, map.rows[id], 'row');

  // The wire codes of the write path (HFY-TSK-245 addendum): every key of WIRE_KEYS is mapped, and none is invented.
  const wire = map.wire;
  if (!wire || typeof wire !== 'object' || Array.isArray(wire)) fail(`gap: ${MAP_PATH} has no "wire" object (the wire codes of the write path)`);
  else {
    for (const key of Object.keys(wire)) {
      if (!WIRE_KEYS.includes(key)) fail(`unknown wire code "${key}": the checker knows ${WIRE_KEYS.length} (WIRE_KEYS in check-sync-catalog.mjs)`);
    }
    for (const key of WIRE_KEYS) checkEntry(key, wire[key], 'wire code');
  }

  const docFile = resolve(root, DOC_PATH);
  if (problems.length === 0) {
    const tables = [
      { start: DOC_START, end: DOC_END, text: renderDoc(map) },
      { start: WIRE_START, end: WIRE_END, text: renderWire(map) },
    ];
    if (writeDoc) {
      const current = existsSync(docFile) ? readFileSync(docFile, 'utf8') : '';
      let next = current;
      for (const t of tables) {
        next = next === null ? null : replaceTable(next, t);
        if (next === null) fail(`${DOC_PATH} has no table markers (${t.start} ... ${t.end})`);
      }
      if (next !== null && next !== current) writeFileSync(docFile, next);
    }
    if (problems.length === 0) {
      if (!existsSync(docFile)) fail(`${DOC_PATH} is missing`);
      else {
        const text = readFileSync(docFile, 'utf8');
        for (const t of tables) {
          const have = extractTable(text, t);
          if (have === null) fail(`${DOC_PATH} has no table markers (${t.start} ... ${t.end})`);
          else if (have !== t.text) fail(`${DOC_PATH} is not what the map renders: run node scripts/ci/check-sync-catalog.mjs --write-doc`);
        }
      }
    }
  }
  return { problems, rows: Object.keys(map.rows).length, wire: wire && typeof wire === 'object' ? Object.keys(wire).length : 0, tests: testCount };
}

// ---- the reference page's table

function suiteLabel(file) {
  const s = SUITES.find((x) => file.startsWith(x.prefix));
  return s ? s.label.split(' (')[0] : '';
}

export function renderDoc(map) {
  const lines = ['| Row | Failure | Tests (file :: name) |', '|---|---|---|'];
  for (const id of Object.keys(map.rows).filter((i) => /^[DS]\d\d$/.test(i)).sort((a, b) => idOrder(a) - idOrder(b))) {
    const row = map.rows[id];
    const tests = (row.tests || []).map((t) => `\`${t.file}\` :: \`${t.name.replace(/\|/g, '\\|')}\` (${suiteLabel(t.file)})`).join('<br>');
    lines.push(`| ${id} | ${String(row.failure || '').replace(/\|/g, '\\|')} | ${tests} |`);
  }
  return lines.join('\n');
}

/** The wire codes table: the refusal, what it means, and its tests. */
export function renderWire(map) {
  const lines = ['| Wire code | Failure | Tests (file :: name) |', '|---|---|---|'];
  for (const key of WIRE_KEYS) {
    const entry = (map.wire || {})[key] || {};
    const tests = (entry.tests || []).map((t) => `\`${t.file}\` :: \`${t.name.replace(/\|/g, '\\|')}\` (${suiteLabel(t.file)})`).join('<br>');
    lines.push(`| \`${key.replace(/\|/g, '\\|')}\` | ${String(entry.failure || '').replace(/\|/g, '\\|')} | ${tests} |`);
  }
  return lines.join('\n');
}

function extractTable(text, t = { start: DOC_START, end: DOC_END }) {
  const a = text.indexOf(t.start);
  const b = text.indexOf(t.end);
  if (a < 0 || b < a) return null;
  return text.slice(a + t.start.length, b).replace(/^\n+|\n+$/g, '');
}

function replaceTable(text, t) {
  const a = text.indexOf(t.start);
  const b = text.indexOf(t.end);
  if (a < 0 || b < a) return null;
  return `${text.slice(0, a + t.start.length)}\n\n${t.text}\n\n${text.slice(b)}`;
}

// ---- command line

function main(argv) {
  let root = DEFAULT_ROOT;
  let writeDoc = false;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--root') root = resolve(argv[(i += 1)] || '');
    else if (argv[i] === '--write-doc') writeDoc = true;
    else {
      console.error(`unknown argument ${argv[i]}\nusage: node scripts/ci/check-sync-catalog.mjs [--root <repo>] [--write-doc]`);
      return 2;
    }
  }
  const { problems, rows, wire, tests } = check({ root, writeDoc });
  if (problems.length) {
    for (const p of problems) console.error(`check-sync-catalog: ${p}`);
    console.error(`check-sync-catalog: ${problems.length} problem(s)`);
    return 1;
  }
  console.log(`check-sync-catalog: ok, ${rows} rows (D01-D${DESKTOP_ROWS}, S01-S${CLOUD_ROWS}), ${wire} wire codes, ${tests} mapped tests`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
