#!/usr/bin/env node
// The sync error catalog test map (HFY-TSK-150, review SI-21; sync.md section 17 as amended by BRD2 section 11.1).
//
// The catalog has 52 desktop rows (D01-D52) and 22 cloud rows (S01-S22). scripts/ci/sync-error-catalog.json maps every row to the
// named tests that trigger it. This script fails when:
//   - a row has no entry, an entry has no test, or a row's failure text is empty (a gap);
//   - the map holds a row ID outside D01-D52 and S01-S22 (an unknown ID);
//   - a mapped test is not declared in its file (a renamed or deleted test), or its file is outside the test suites;
//   - docs/reference/sync-error-catalog.md is not what this script renders from the map (a drift).
// It reads files and nothing else: no install, no network, no CodeArtifact (HFY-R62), so it runs in the ci.manifest.yaml `tests` list.
//
// A test name is the declaration the file holds, found by file type:
//   .py   the method name: `def test_x(self)`
//   .js   the exact title string of an `it("...")` or `test("...")` call (the title has no template placeholders)
//   .sh   the label of a `CURRENT="..."` line in the infra test runner
//
// Usage: node scripts/ci/check-sync-catalog.mjs [--root <repo>] [--write-doc]
//   --write-doc  rewrite the table in the reference page from the map, then check
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(HERE, '..', '..');
export const MAP_PATH = 'scripts/ci/sync-error-catalog.json';
export const DOC_PATH = 'docs/reference/sync-error-catalog.md';
export const DOC_START = '<!-- sync-error-catalog:start (generated by scripts/ci/check-sync-catalog.mjs --write-doc) -->';
export const DOC_END = '<!-- sync-error-catalog:end -->';

export const DESKTOP_ROWS = 52;
export const CLOUD_ROWS = 22;

/** Where a test may live, with the suite that runs it (the label in the reference page). */
export const SUITES = [
  { prefix: 'gramps/tests/unit/', label: 'Gramps unit (python3 -m unittest discover gramps/tests/unit)' },
  { prefix: 'gramps/tests/e2e/', label: 'Gramps e2e (gramps/tests/e2e/run.sh, Gramps 6.0.6 and the dev server)' },
  { prefix: 'gramps/tests/gramps/', label: 'Gramps lane (gramps/tests/gramps/run.sh, Gramps 6.0.6)' },
  { prefix: 'api/test/', label: 'api (cd api && npm test)' },
  { prefix: 'scripts/infra/test/', label: 'infra (bash scripts/infra/test/run.sh)' },
];

export function expectedIds() {
  const ids = [];
  for (let i = 1; i <= DESKTOP_ROWS; i += 1) ids.push(`D${String(i).padStart(2, '0')}`);
  for (let i = 1; i <= CLOUD_ROWS; i += 1) ids.push(`S${String(i).padStart(2, '0')}`);
  return ids;
}

function idOrder(id) {
  return (id[0] === 'D' ? 0 : 1000) + Number(id.slice(1));
}

// ---- finding a declaration in a file

function unquote(literal) {
  const q = literal[0];
  const body = literal.slice(1, -1);
  if (q === '`') return body.includes('${') ? null : body.replace(/\\(.)/g, '$1');
  try {
    return q === '"' ? JSON.parse(literal) : JSON.parse(`"${body.replace(/\\'/g, "'").replace(/"/g, '\\"')}"`);
  } catch {
    return null;
  }
}

export function declaredNames(file, text) {
  const names = new Set();
  if (file.endsWith('.py')) {
    for (const m of text.matchAll(/^[ \t]*(?:async[ \t]+)?def[ \t]+([A-Za-z_][A-Za-z0-9_]*)[ \t]*\(/gm)) names.add(m[1]);
  } else if (/\.(?:m?js|cjs)$/.test(file)) {
    const re = /\b(?:it|test)(?:\.\w+)?\(\s*("(?:[^"\\\n]|\\.)*"|'(?:[^'\\\n]|\\.)*'|`(?:[^`\\]|\\.)*`)/g;
    for (const m of text.matchAll(re)) {
      const title = unquote(m[1]);
      if (title !== null) names.add(title);
    }
  } else if (file.endsWith('.sh')) {
    for (const m of text.matchAll(/^\s*CURRENT="([^"\n]*)"/gm)) names.add(m[1]);
  }
  return names;
}

// ---- the check

export function check({ root = DEFAULT_ROOT, writeDoc = false } = {}) {
  const problems = [];
  const fail = (msg) => problems.push(msg);
  const mapFile = resolve(root, MAP_PATH);
  if (!existsSync(mapFile)) return { problems: [`${MAP_PATH} is missing`], rows: 0, tests: 0 };
  let map;
  try {
    map = JSON.parse(readFileSync(mapFile, 'utf8'));
  } catch (err) {
    return { problems: [`${MAP_PATH} is not JSON (${err.message})`], rows: 0, tests: 0 };
  }
  if (!map || typeof map !== 'object' || map.version !== 1 || !map.rows || typeof map.rows !== 'object' || Array.isArray(map.rows)) {
    return { problems: [`${MAP_PATH} must be {"version": 1, "rows": {...}}`], rows: 0, tests: 0 };
  }

  const expected = new Set(expectedIds());
  for (const id of Object.keys(map.rows)) {
    if (!expected.has(id)) fail(`unknown row ID ${id}: the catalog has D01-D${DESKTOP_ROWS} and S01-S${String(CLOUD_ROWS).padStart(2, '0')}`);
  }

  const fileCache = new Map();
  const namesOf = (file) => {
    if (!fileCache.has(file)) {
      const full = resolve(root, file);
      fileCache.set(file, existsSync(full) ? declaredNames(file, readFileSync(full, 'utf8')) : null);
    }
    return fileCache.get(file);
  };

  let testCount = 0;
  for (const id of expectedIds()) {
    const row = map.rows[id];
    if (!row) {
      fail(`gap: ${id} has no entry`);
      continue;
    }
    if (typeof row.failure !== 'string' || !row.failure.trim()) fail(`gap: ${id} has no failure text`);
    if (!Array.isArray(row.tests) || row.tests.length === 0) {
      fail(`gap: ${id} has no test`);
      continue;
    }
    const seen = new Set();
    for (const t of row.tests) {
      testCount += 1;
      if (!t || typeof t.file !== 'string' || typeof t.name !== 'string' || !t.file || !t.name) {
        fail(`${id}: a test entry needs a file and a name`);
        continue;
      }
      const tag = `${id}: ${t.file} :: ${t.name}`;
      if (seen.has(`${t.file}::${t.name}`)) fail(`${tag} is listed twice`);
      seen.add(`${t.file}::${t.name}`);
      if (t.file.includes('..') || t.file.startsWith('/')) {
        fail(`${tag}: the file must be a path inside the repository`);
        continue;
      }
      if (!SUITES.some((s) => t.file.startsWith(s.prefix))) {
        fail(`${tag}: the file is not in a test suite (${SUITES.map((s) => s.prefix).join(', ')})`);
        continue;
      }
      const names = namesOf(t.file);
      if (names === null) fail(`${tag}: the file does not exist`);
      else if (!names.has(t.name)) fail(`${tag}: no such test in the file`);
    }
  }

  const docFile = resolve(root, DOC_PATH);
  if (problems.length === 0) {
    const doc = renderDoc(map);
    if (writeDoc) {
      const current = existsSync(docFile) ? readFileSync(docFile, 'utf8') : '';
      const next = replaceTable(current, doc);
      if (next === null) fail(`${DOC_PATH} has no table markers (${DOC_START} ... ${DOC_END})`);
      else if (next !== current) writeFileSync(docFile, next);
    }
    if (!existsSync(docFile)) fail(`${DOC_PATH} is missing`);
    else {
      const text = readFileSync(docFile, 'utf8');
      const have = extractTable(text);
      if (have === null) fail(`${DOC_PATH} has no table markers (${DOC_START} ... ${DOC_END})`);
      else if (have !== doc) fail(`${DOC_PATH} is not what the map renders: run node scripts/ci/check-sync-catalog.mjs --write-doc`);
    }
  }
  return { problems, rows: Object.keys(map.rows).length, tests: testCount };
}

// ---- the reference page's table

function suiteLabel(file) {
  const s = SUITES.find((x) => file.startsWith(x.prefix));
  return s ? s.label.split(' (')[0] : '';
}

export function renderDoc(map) {
  const lines = ['| Row | Failure | Tests (file :: name) |', '|---|---|---|'];
  for (const id of Object.keys(map.rows).filter((i) => /^[DS]\d\d$/.test(i)).sort((a, b) => idOrder(a) - idOrder(b))) {
    const row = map.rows[id];
    const tests = (row.tests || []).map((t) => `\`${t.file}\` :: \`${t.name.replace(/\|/g, '\\|')}\` (${suiteLabel(t.file)})`).join('<br>');
    lines.push(`| ${id} | ${String(row.failure || '').replace(/\|/g, '\\|')} | ${tests} |`);
  }
  return lines.join('\n');
}

function extractTable(text) {
  const a = text.indexOf(DOC_START);
  const b = text.indexOf(DOC_END);
  if (a < 0 || b < a) return null;
  return text.slice(a + DOC_START.length, b).replace(/^\n+|\n+$/g, '');
}

function replaceTable(text, table) {
  const a = text.indexOf(DOC_START);
  const b = text.indexOf(DOC_END);
  if (a < 0 || b < a) return null;
  return `${text.slice(0, a + DOC_START.length)}\n\n${table}\n\n${text.slice(b)}`;
}

// ---- command line

function main(argv) {
  let root = DEFAULT_ROOT;
  let writeDoc = false;
  for (let i = 0; i < argv.length; i += 1) {
    if (argv[i] === '--root') root = resolve(argv[(i += 1)] || '');
    else if (argv[i] === '--write-doc') writeDoc = true;
    else {
      console.error(`unknown argument ${argv[i]}\nusage: node scripts/ci/check-sync-catalog.mjs [--root <repo>] [--write-doc]`);
      return 2;
    }
  }
  const { problems, rows, tests } = check({ root, writeDoc });
  if (problems.length) {
    for (const p of problems) console.error(`check-sync-catalog: ${p}`);
    console.error(`check-sync-catalog: ${problems.length} problem(s)`);
    return 1;
  }
  console.log(`check-sync-catalog: ok, ${rows} rows (D01-D${DESKTOP_ROWS}, S01-S${CLOUD_ROWS}), ${tests} mapped tests`);
  return 0;
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) process.exit(main(process.argv.slice(2)));
