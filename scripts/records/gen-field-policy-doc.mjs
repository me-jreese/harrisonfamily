#!/usr/bin/env node
// Render docs/reference/field-policy.md from api/src/records/field-policy.js (HFY-TSK-284, edit-docs).
//
//   node scripts/records/gen-field-policy-doc.mjs           write the page
//   node scripts/records/gen-field-policy-doc.mjs --check   exit 1 when the page differs from the table, write nothing
//
// The only input is the policy table the API itself loads (DEFAULT_FIELD_POLICY.document(), Q2_15_ROWS, STRUCTURE_ROWS and the
// never-type lists). It reads no data. The output carries a sha256 of that input, so a change to the table shows up as a changed
// header even before the rows are compared. `--root <dir>` moves the repository root (tests use it for the output path only).
//
// It needs no installed package, so the io-kit CI `test` job, which installs nothing, can run it. The table's import chain
// (records/guard.js, then http.js) reaches two packages from the private registry, `@io-kit/content` and `@io-kit/comments`,
// for one error class each, which http.js uses only to map an error to a response. Before it imports the table, the generator
// stands an empty error class in for each of those two imports of http.js (a module resolve hook, `standInHttpPackages`). Any
// other package import on the chain still fails with ERR_MODULE_NOT_FOUND, and the test that runs this in a copy with no
// node_modules catches it.
import { createHash } from "node:crypto";
import { existsSync, mkdirSync, readFileSync, realpathSync, writeFileSync } from "node:fs";
import * as nodeModule from "node:module";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const HERE = dirname(fileURLToPath(import.meta.url));
const DEFAULT_ROOT = resolve(HERE, "..", "..");
export const OUT_PATH = "docs/reference/field-policy.md";

const CLASSES = ["Person", "Family", "Event", "Place", "Source", "Citation", "Repository", "Media", "Note"];
const WHEN_TEXT = {
  birthLike: "the event is birth-like",
  dayMonthInValue: "the value carries a day or month",
  localPlace: "the place is below the administrative level",
  administrativePlace: "the place is an administrative type",
  neverPlaceType: "the place type is a withheld one",
  neverAttribute: "the attribute type is a withheld one",
  emailUrl: "the URL is an e-mail URL",
  nonLinkUrl: "the URL is not one of the link kinds",
  mergedGid: "the attribute is the merged-Gramps-IDs key",
};

const cell = (s) => String(s).replace(/\|/g, "\\|");
const code = (c) => `\`${c}\``;

/** Render the page text from the policy module. Pure given the module. */
export function render(mod) {
  const doc = mod.DEFAULT_FIELD_POLICY.document();
  const hash = createHash("sha256")
    .update(JSON.stringify({ doc, q: mod.Q2_15_ROWS, n: mod.NEVER_TYPE_VALUES, l: mod.LINK_URL_KINDS }))
    .digest("hex");
  const out = [];
  out.push("# Field policy");
  out.push("");
  out.push(`<!-- Generated by scripts/records/gen-field-policy-doc.mjs from api/src/records/field-policy.js. Do not edit by hand: change the table, regenerate, and commit both. Input sha256: ${hash} -->`);
  out.push("");
  out.push("Who may change which field of a record on the website, and how. This page is generated from the policy table in [`api/src/records/field-policy.js`](../../api/src/records/field-policy.js), the table the API loads; `node scripts/records/gen-field-policy-doc.mjs --check` fails when the page and the table differ, and a test runs it. For why the table exists and how a change moves from the editor to the family tree, see [How editing and suggested changes work](../explanation/editing-and-proposals.md). For the routes that apply it, see [Family API: Editing API changes](api.md#editing-api-changes).");
  out.push("");
  out.push("## The codes");
  out.push("");
  out.push("| Code | Meaning |");
  out.push("| --- | --- |");
  out.push(`| ${code("direct")} | The change saves now. |`);
  out.push(`| ${code("proposal")} | The change goes to review as a suggestion; an admin approves it. |`);
  out.push(`| ${code("admin")} | A member cannot even suggest it. Only an admin can make it on the web. |`);
  out.push(`| ${code("desk")} | Not editable on the web. It is done in Gramps desktop and syncs up. |`);
  out.push(`| ${code("derived")} | Computed by the server. A client write is refused. |`);
  out.push(`| ${code("never")} | Refused on every path, admins included (R-18). Gramps desktop keeps it. |`);
  out.push("");
  out.push("The columns are the viewer: `own` is a member editing their own record, `other` a member editing anyone else's, `admin` an admin. A pointer that matches no row is a `proposal` for a member and `direct` for an admin. The most specific row wins: a `never`, `desk` or `derived` row beats a plain one, then the pattern with more literal segments, then the row listed later.");
  out.push("");
  out.push("Pointer patterns are RFC 6901 paths where `*` is one segment, `**` is any subtree (including the node itself), and `{a,b}` is a choice. A row with a condition applies only when the condition holds; with no way to judge the condition, the stricter row applies.");
  out.push("");
  out.push("## The table");
  out.push("");
  for (const cls of CLASSES) {
    const rows = doc.rows.filter((r) => r.cls === cls);
    out.push(`### ${cls}`);
    out.push("");
    out.push("| Pointer | own | other | admin | When | Switch |");
    out.push("| --- | --- | --- | --- | --- | --- |");
    for (const r of rows) {
      const when = (r.when ?? []).map((w) => WHEN_TEXT[w] ?? w).join("; ");
      out.push(`| ${code(cell(r.pointer || "(whole record)"))} | ${code(r.own)} | ${code(r.other)} | ${code(r.admin)} | ${cell(when)} | ${r.group ? code(r.group) : ""} |`);
    }
    out.push("");
  }
  out.push("## Structure rules");
  out.push("");
  out.push("These judge the ops of a whole submission, not one pointer.");
  out.push("");
  out.push("| Kind | own | other | admin |");
  out.push("| --- | --- | --- | --- |");
  for (const k of doc.structure) out.push(`| ${code(k.kind)} | ${code(k.own)} | ${code(k.other)} | ${code(k.admin)} |`);
  out.push("");
  out.push("## Switches for open questions (Q2-15)");
  out.push("");
  out.push("Each row below is one switch that changes data, not code. The default is the first answer; `createFieldPolicy({ answers })` takes another.");
  out.push("");
  out.push("| Switch | What it decides | Default (own / other) | Other answers |");
  out.push("| --- | --- | --- | --- |");
  for (const r of mod.Q2_15_ROWS) {
    const alts = Object.entries(r.alternatives).map(([k, v]) => `${code(k)}: ${Object.entries(v).map(([who, c]) => `${who} ${code(c)}`).join(", ")}`).join("; ");
    out.push(`| ${code(r.id)} | ${cell(r.label)} | ${code(r.own)} / ${code(r.other)} | ${alts} |`);
  }
  out.push("");
  out.push("## Withheld types");
  out.push("");
  out.push("A row marked with a withheld-type condition fires when the value names one of these Gramps type numbers (the values of the Gramps type tables).");
  out.push("");
  out.push("| Type | Withheld values |");
  out.push("| --- | --- |");
  for (const [k, v] of Object.entries(mod.NEVER_TYPE_VALUES)) out.push(`| ${code(k)} | ${v.map((n) => `\`${n}\``).join(", ")} |`);
  out.push("");
  out.push(`A Person link may be written on the web only as a Web Home URL, or a Custom URL whose string is one of ${mod.LINK_URL_KINDS.map(code).join(", ")}. Every other URL type is ${code("desk")}, and an e-mail URL is ${code("never")}.`);
  out.push("");
  return out.join("\n");
}

// The packages api/src/http.js imports only for its error mapping, and the stand-in for each (see the header).
const HTTP_STAND_INS = {
  "@io-kit/content": "export class ContentError extends Error {}",
  "@io-kit/comments": "export class CommentError extends Error {}",
};
const HOOK_SOURCE = `const S = ${JSON.stringify(HTTP_STAND_INS)};
export function resolve(specifier, context, next) {
  if (Object.hasOwn(S, specifier) && typeof context.parentURL === "string" && context.parentURL.endsWith("/api/src/http.js")) {
    return { url: "data:text/javascript," + encodeURIComponent(S[specifier]), shortCircuit: true };
  }
  return next(specifier, context);
}`;
let hooked = null;

/**
 * Register HOOK_SOURCE once per process: in-thread with module.registerHooks (Node 22.15 and later), else off-thread with
 * module.register. The one hook body serves both, because it returns whatever `next` returns, value or promise.
 */
export function standInHttpPackages() {
  hooked ??= (async () => {
    const url = `data:text/javascript,${encodeURIComponent(HOOK_SOURCE)}`;
    if (typeof nodeModule.registerHooks === "function") nodeModule.registerHooks({ resolve: (await import(url)).resolve });
    else nodeModule.register(url);
  })();
  return hooked;
}

export async function load(root = DEFAULT_ROOT) {
  await standInHttpPackages();
  return import(pathToFileURL(join(root, "api/src/records/field-policy.js")).href);
}

export async function check(root = DEFAULT_ROOT, mod) {
  const text = render(mod ?? (await load(root)));
  const file = join(root, OUT_PATH);
  if (!existsSync(file)) return [`${OUT_PATH} is missing`];
  return readFileSync(file, "utf8") === text ? [] : [`${OUT_PATH} differs from the table in api/src/records/field-policy.js`];
}

async function main(argv) {
  let root = DEFAULT_ROOT;
  let checkOnly = false;
  for (let i = 0; i < argv.length; i++) {
    if (argv[i] === "--check") checkOnly = true;
    else if (argv[i] === "--root" && argv[i + 1]) root = resolve(argv[++i]);
    else {
      console.error("usage: gen-field-policy-doc.mjs [--check] [--root <repository root>]");
      return 2;
    }
  }
  const mod = await load(DEFAULT_ROOT);
  if (checkOnly) {
    const problems = await check(root, mod);
    if (problems.length) {
      for (const p of problems) console.error(`drift: ${p}`);
      console.error("run `node scripts/records/gen-field-policy-doc.mjs` and commit the result");
      return 1;
    }
    console.log("field-policy.md is current");
    return 0;
  }
  mkdirSync(dirname(join(root, OUT_PATH)), { recursive: true });
  writeFileSync(join(root, OUT_PATH), render(mod));
  console.log(`wrote ${OUT_PATH}`);
  return 0;
}

// Compare real paths: Node runs the main module from its real path, so a path through a symlink (macOS /var, /tmp) would
// otherwise never match, and the CLI would exit 0 having checked nothing.
const isMain = () => {
  try {
    return realpathSync(resolve(process.argv[1])) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
};
if (process.argv[1] && isMain()) process.exitCode = await main(process.argv.slice(2));
