// HFY design-system pass (F2): self-hosted brand faces. Google Fonts is NOT used: it would see every family member's IP and
// user agent on private pages (sign-in included), it would need extra CSP origins on the auth edge, it adds connections,
// and it breaks the installed PWA offline. The faces come from exact-pinned @fontsource devDependencies (OFL-1.1).
//
// fontFiles() -> the 12 latin + latin-ext woff2 files, content-hashed as fonts/<base>.<sha256-8>.woff2 so the service worker
// can serve them cache-first, plus the three OFL licence texts as fonts/LICENSE-<family>.txt.
// fontFaceCss() -> the @font-face rules (the `hfy:fonts` virtual import). Family names are the ones the token stacks name
// ("Source Sans 3", "Libre Caslon Text", "Source Code Pro"); fontsource-variable's own CSS says "… Variable", so it is not reused.
// preloadHref() -> the one face worth preloading: the UI face, latin, upright.
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const pkgDir = (name) => join(here, "node_modules", ...name.split("/"));

// family, package, the faces to ship (subset x style x weight). Variable faces take their weight range from metadata.json.
const FAMILIES = [
  {
    family: "Source Sans 3",
    slug: "source-sans-3",
    pkg: "@fontsource-variable/source-sans-3",
    faces: [
      { file: "wght-normal", style: "normal" },
      { file: "wght-italic", style: "italic" }
    ]
  },
  {
    family: "Libre Caslon Text",
    slug: "libre-caslon-text",
    pkg: "@fontsource/libre-caslon-text",
    faces: [
      { file: "400-normal", style: "normal", weight: "400" },
      { file: "400-italic", style: "italic", weight: "400" },
      { file: "700-normal", style: "normal", weight: "700" }
    ]
  },
  {
    family: "Source Code Pro",
    slug: "source-code-pro",
    pkg: "@fontsource-variable/source-code-pro",
    faces: [{ file: "wght-normal", style: "normal" }]
  }
];
const SUBSETS = ["latin-ext", "latin"]; // latin last: for overlapping code points the later @font-face wins
const PRELOAD = "source-sans-3-latin-wght-normal";

const sha8 = (buf) => createHash("sha256").update(buf).digest("hex").slice(0, 8);

let cache = null;
function collect() {
  if (cache) return cache;
  const files = new Map(); // fonts/<name> -> Buffer
  const rules = [];
  let preload = null;
  for (const fam of FAMILIES) {
    const dir = pkgDir(fam.pkg);
    const meta = JSON.parse(readFileSync(join(dir, "metadata.json"), "utf8"));
    const unicode = JSON.parse(readFileSync(join(dir, "unicode.json"), "utf8"));
    if (meta.family !== fam.family) throw new Error(`${fam.pkg}: metadata family is "${meta.family}", expected "${fam.family}"`);
    const range = meta.variable && meta.variable.wght ? `${meta.variable.wght.min} ${meta.variable.wght.max}` : null;
    for (const subset of SUBSETS) {
      if (!unicode[subset]) throw new Error(`${fam.pkg}: unicode.json has no "${subset}" range`);
      for (const face of fam.faces) {
        const base = `${fam.slug}-${subset}-${face.file}`;
        const buf = readFileSync(join(dir, "files", `${base}.woff2`));
        const name = `${base}.${sha8(buf)}.woff2`;
        files.set(name, buf);
        if (base === PRELOAD) preload = `/fonts/${name}`;
        const weight = face.weight || range;
        if (!weight) throw new Error(`${fam.pkg}: no weight for ${base}`);
        rules.push(
          `@font-face{font-family:"${fam.family}";font-style:${face.style};font-weight:${weight};font-display:swap;` +
            `src:url(/fonts/${name}) format("woff2");unicode-range:${unicode[subset]}}`
        );
      }
    }
    files.set(`LICENSE-${fam.slug}.txt`, readFileSync(join(dir, "LICENSE")));
  }
  if (!preload) throw new Error(`preload face ${PRELOAD} not found`);
  const css = `/* self-hosted brand faces (OFL-1.1, see /fonts/LICENSE-*.txt), generated by islands/fonts.mjs */\n${rules.join("\n")}\n`;
  cache = { files, css, preload };
  return cache;
}

/** Map of file name (inside <site>/fonts/) -> contents. */
export const fontFiles = () => collect().files;
/** The @font-face CSS behind `@import "hfy:fonts"`. */
export const fontFaceCss = () => collect().css;
/** Root-relative href of the preloaded UI face (Source Sans 3, latin, upright). */
export const preloadHref = () => collect().preload;
/** The family names the @font-face rules declare (the token stacks name them). */
export const FONT_FAMILIES = FAMILIES.map((f) => f.family);
